def test_the_metering_run_will_not_dispatch_without_a_ledger(tmp_path, corpus):
    """Elsewhere a missing ledger is a warning. Here it is the whole question.

    A metering trial without `--cost-ledger` buys audio calls to answer a
    question it then cannot answer, which is the one outcome worse than not
    running it.
    """
    document = _document(tmp_path / "prereg.md", corpus=corpus)
