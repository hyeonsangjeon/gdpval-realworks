def test_a_rehearsal_ledger_refuses_to_take_a_paid_row(tmp_path, corpus):
    """One file, one kind. A mixed total is part invoice and part dress run.

    The refusal is checked from the rehearsal side because that is the side
    that can be tested without buying anything, and the rule is symmetric: the
    dispatcher compares the run's kind against the kinds already in the file.
    """
    document = _document(tmp_path / "prereg.md", corpus=corpus)
    ledger = tmp_path / "probe.cost_ledger.sqlite3"
    assert _run(tmp_path, corpus, document, cost_ledger=ledger)[0] == 0

    # Re-open the same file and put a measured row in it, the way a paid run
    # would. No model is called: only the bookkeeping shape matters here.
    from core.cost_receipts import (
        RETRY_NONE,
        STAGE_PERCEPTION,
        CostReceiptLedger,
        make_call_id,
    )

    with CostReceiptLedger(
        ledger, run_id="paid-run", price_table=load_receipt_price_table()
    ) as paid:
        paid.reserve(
            call_id=make_call_id(
                run_id="paid-run",
                task_id="audio_accuracy_diagnostic",
                stage=STAGE_PERCEPTION,
                retry_kind=RETRY_NONE,
                attempt_index=0,
                sequence=99,
            ),
            task_id="audio_accuracy_diagnostic",
            stage=STAGE_PERCEPTION,
            retry_kind=RETRY_NONE,
            provider="azure",
            requested_model="gpt-audio-1.5",
            deployment="gpt-audio-1.5",
            api_version="2025-04-01-preview",
            request_sha256="0" * 64,
        )
        # Asserted before the dispatch, so a code 3 for some unrelated reason
        # cannot be read as this refusal firing.
        assert measure.ledger_record_kinds(paid) >= {"rehearsal", "measured"}

    code, _ = _run(tmp_path, corpus, document, cost_ledger=ledger)
    assert code == 3


# ── a broken verdict is not a lost cost row ──────────────────────────────


class _StubThatBreaks:
    """Answers badly on purpose: one unparseable reply, one refusal to judge.

    337's replies mostly failed to parse, and a metering path that settled
    after parsing would have lost exactly those calls -- the calls that were
    charged for. Both shapes are produced here because they take different
    branches in ``AudioPerception.judge``: the first raises out of the envelope
    parser, the second returns normally with a verdict that declines.
    """

    def __init__(self, claims) -> None:
        self._order = [claim.criterion for claim in claims]
        self.requests: list[dict[str, Any]] = []
        self.chat = type("_Chat", (), {"completions": self})()

    def create(self, **kwargs: Any) -> Any:
        self.requests.append(kwargs)
        text = ""
        b64_chars = 0
        for part in kwargs["messages"][0]["content"]:
            if part.get("type") == "text":
                text = part["text"]
            elif part.get("type") == "input_audio":
                b64_chars = len((part.get("input_audio") or {}).get("data") or "")
        first = self._order and self._order[0] in text
        body = (
            "I listened to the clip and I think ... " if first
            else json.dumps(
                {
                    "verdict": "judge_error",
                    "partial_score": 0.0,
                    "evidence": "",
                    "confidence": 0.0,
                    "reasoning": "stub: declining to judge",
                }
            )
        )
        return measure._StubResponse(body, b64_chars=b64_chars)


def test_an_unreadable_reply_and_a_refusal_both_keep_their_cost_rows(
    tmp_path, corpus, monkeypatch
):
    """The question this trial asks is about rows, not about verdicts.

    Neither call produced a judgement, so the script exits 2: nothing was
    measured. That is the *accuracy* question going unanswered, and it is the
    exit code 337 would have earned. The cost question is answered anyway --
    both calls were sent, both consumed tokens, both are on the ledger, and
    the receipt is closed from a ``finally`` that runs on this path too.

    Failing here would mean a run's spend disappears exactly when its replies
    break, which is the shape of run 34008840627: 52 of its calls produced no
    verdict and every one of them was paid for.
    """
    monkeypatch.setattr(measure, "TruthfulStub", _StubThatBreaks)
    document = _document(tmp_path / "prereg.md", corpus=corpus)
    code, report_path = _run(tmp_path, corpus, document)
    assert code == 2

    report = json.loads(report_path.read_text(encoding="utf-8"))
    errors = [call["judge_error"] for call in report["calls"]]
    assert all(errors), errors
    assert any(error.startswith("format_error:") for error in errors), errors
    assert "sub_judge_declined" in errors, errors

    assert report["cost"]["model_calls"] == 2
    assert report["cost"]["ledger"]["rows"] == 2
    assert Path(report["cost"]["ledger"]["path"]).is_file()

    outcome = checker.check(report_path)
    seventh = _condition(outcome, 7)
    assert seventh["result"] == "pass"
    assert seventh["data"]["calls_with_judge_error"] == 2
    assert outcome["counts"]["failed"] == 0
    assert outcome["verdict"] == checker.VERDICT_REHEARSAL_OK


def test_the_accuracy_of_a_broken_run_is_not_what_decides_it(
    tmp_path, corpus, monkeypatch
):
    """Zero answered claims, and the metering verdict is still ok.

    342 §1 says accuracy is 337/338's question and not this one. If a run
    where nothing was judged could not pass, the trial would be measuring the
    sub-judge again by accident -- and the two exit codes are how the two
    questions stay apart: 2 from the measurement script, 0 from the checker.
    """
    monkeypatch.setattr(measure, "TruthfulStub", _StubThatBreaks)
    document = _document(tmp_path / "prereg.md", corpus=corpus)
