"""The metering run has to go all the way through before anything is bought.

340 found that 337's ten paid audio calls left no ledger row: the meter was
never in the client stack, so `pricing_complete`, `unpriced_models` and the
dollar figure in that report were four constants this script wrote afterwards.
342 registers a two-call trial that would show the path reconnected.

A trial that has only ever been described is not a trial. This file runs it --
render, encode, prompt, wire, meter, reserve, settle, price, receipt, report,
check -- with no network and no credential, and then asks the questions 342 §6
says the paid run will be asked. What it can prove is that the plumbing carries
a row from one end to the other; what it cannot prove is anything at all about
`gpt-audio-1.5`, which is why every artifact it produces says `rehearsal` and
every row in its ledger says `provider: stub`.

The corpus here is **synthetic**: two tones, not 330's speech. The pinned clips
are a CI artifact and eSpeak is not installed on every machine that runs these
tests, and a corpus regenerated by a different eSpeak is exactly what
`load_speech_corpus` is built to refuse. So this file builds its own, with its
own manifest and its own rehearsal document, and never points the real
pre-registration at it -- 342's document stays pinned to 330's manifest, and
the swap-detection test below is the reason that pin exists.
"""

