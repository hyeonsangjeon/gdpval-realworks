def test_the_report_records_what_it_was_held_to_without_copying_it_twice(
    tmp_path, corpus
):
    """Provenance with a single home for each digest.

    Two copies of a fingerprint eventually disagree, and when they do there is
    no way to tell which one is the right one. So the metering block carries
    only what has nowhere else to live; the clip digests, the model and the
    price table stay where they already were.
    """
    document = _document(tmp_path / "prereg.md", corpus=corpus)
    _, report_path = _run(tmp_path, corpus, document)
    report = json.loads(report_path.read_text(encoding="utf-8"))
    block = report["metering"]

    assert block["diagnostic_kind"] == measure.AUDIO_COST_METERING_KIND
    assert block["preregistration"]["sha256"] == hashlib.sha256(
        document.read_bytes()
    ).hexdigest()
    assert block["speech_manifest"]["sha256"] == corpus["sha256"]
    assert block["grading_config"]["sha256"] == hashlib.sha256(
        measure.PINNED_CONFIG.read_bytes()
    ).hexdigest()

    serialized = json.dumps(block)
    assert report["cost"]["price_table"]["sha256"] not in serialized
    assert report["pins"]["grader_source_sha256"] not in serialized
    for digest in report["clip_sha256"].values():
        assert digest not in serialized
