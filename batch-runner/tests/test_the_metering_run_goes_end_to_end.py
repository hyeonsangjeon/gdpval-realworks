def test_a_substituted_corpus_is_caught_by_the_manifest_pin(tmp_path, corpus, capsys):
    """The clips check out. Against their own manifest, which is the point.

    A corpus swapped for one regenerated this morning is internally consistent
    and passes every digest ``load_speech_corpus`` checks, because the file
    making the claims is the file being checked. The document's pin is what
    turns that consistency into identity.
    """
    swapped = tmp_path / "swapped-manifest.json"
    manifest = json.loads(corpus["manifest"].read_text(encoding="utf-8"))
    manifest["note_added_after_pinning"] = "one byte of drift"
    swapped.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    assert hashlib.sha256(swapped.read_bytes()).hexdigest() != corpus["sha256"]

    document = _document(tmp_path / "prereg.md", corpus=corpus)
    code, _ = _run(tmp_path, corpus, document, speech_set=swapped)
    assert code == 3
    error = capsys.readouterr().err
    assert "not the speech manifest" in error
    assert "which is the check a substituted corpus" in error


