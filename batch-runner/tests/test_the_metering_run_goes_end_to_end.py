#: 16 kHz mono, which is what the grading path delivers and what the manifest
#: pins. The tone frequency is irrelevant to everything downstream -- the stub
#: does not listen -- but the two clips are given different lengths on purpose
#: so their payloads, and therefore their ``request_sha256``, differ. A
#: duplicate row is then visible at the payload level and not only by call id.
SAMPLE_RATE_HZ = 16000
CLIP_SECONDS = {"crate": 3.0, "shelf": 2.5}

#: The two claims 342 §2 fixes, and the two that pair with them. All four are
#: in the manifest because ``load_speech_corpus`` requires the corpus to be
#: balanced and every pair to hold one true and one false; the run narrows to
#: the two named in the document, which is the same narrowing 337's pilot did.
NARROWED_TO = ("crate_seventeen", "shelf_fifty")


def _render_clip(path: Path, seconds: float) -> dict[str, Any]:
    frames = int(seconds * SAMPLE_RATE_HZ)
    body = b"".join(
        struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440.0 * n / SAMPLE_RATE_HZ)))
        for n in range(frames)
    )
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(SAMPLE_RATE_HZ)
        handle.writeframes(body)
    raw = path.read_bytes()
    return {
        "file": path.name,
        "sha256": hashlib.sha256(raw).hexdigest(),
        "bytes": len(raw),
        "format": "wav",
        "channels": 1,
        "sample_width_bytes": 2,
        "sample_rate_hz": SAMPLE_RATE_HZ,
        "frames": frames,
        "seconds": round(frames / SAMPLE_RATE_HZ, 4),
    }


def _claim(claim_id: str, pair_id: str, clip_id: str, word: str, holds: bool):
    return {
        "claim_id": claim_id,
        "pair_id": pair_id,
        "clip_id": clip_id,
        "family": "confusable_number",
        "criterion": f"The speaker states a quantity of {word}.",
        "holds": holds,
        "because": f"synthetic rehearsal claim, {'true' if holds else 'false'}",
    }


@pytest.fixture(scope="module")
def corpus(tmp_path_factory) -> dict[str, Any]:
    """Two tones, a manifest that pins them, and the digest of that manifest.

    Module-scoped: the clips are read-only for every test here and rendering
    them is the slowest thing in the file.
    """
    root = tmp_path_factory.mktemp("rehearsal-corpus")
    clips = root / "clips"
    clips.mkdir()
    manifest = {
        "kind": "synthetic-rehearsal-corpus",
        "not_the_pinned_set": (
            "Tones, not speech, generated by the test suite. This exists so "
            "the metering path can be run end to end offline. It is not 330's "
            "corpus and no accuracy may be read off it."
        ),
        "clips": [
            {
                "clip_id": clip_id,
                "sent": _render_clip(clips / f"{clip_id}.sent.wav", seconds),
            }
            for clip_id, seconds in CLIP_SECONDS.items()
        ],
        "claims": [
            _claim("crate_seventeen", "crate_number", "crate", "seventeen", True),
            _claim("crate_seventy", "crate_number", "crate", "seventy", False),
            _claim("shelf_fifteen", "shelf_number", "shelf", "fifteen", True),
            _claim("shelf_fifty", "shelf_number", "shelf", "fifty", False),
        ],
    }
    path = root / "rehearsal-manifest.json"
    path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return {
        "manifest": path,
        "clips": clips,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def _document(
    path: Path,
    *,
    corpus: dict[str, Any],
    kind: str = measure.AUDIO_COST_METERING_KIND,
    grader: str | None = None,
    price: str | None = None,
    manifest: str | None = None,
    claims: tuple[str, ...] = NARROWED_TO,
) -> Path:
    """A rehearsal document in the shape the dispatcher reads.

    Every pin is overridable because the refusals below are exactly the cases
    where one of them is wrong, and a test that could not write a wrong
    document could not show the dispatcher noticing.
    """
    if grader is None:
        grader = measure.grader_source_hash(measure.PINNED_CONFIG)
    if price is None:
        price = load_receipt_price_table().sha256
    if manifest is None:
        manifest = corpus["sha256"]
    listed = ", ".join(f"`{claim_id}`" for claim_id in claims)
    path.write_text(
        "# REHEARSAL ONLY — this is not a pre-registration\n"
        "\n"
        "Written by the test suite. It pins a synthetic corpus of tones and\n"
        "buys nothing. 342's real document is not this file.\n"
        "\n"
        "| | 값 |\n"
        "|---|---|\n"
        f"| 진단 종류 | `{kind}` |\n"
        f"| 채점기 지문 | `{grader}` |\n"
        f"| 가격표 지문 | `{price}` |\n"
        f"| 매니페스트 지문 | `{manifest}` |\n"
        f"| 시험 문항 | {listed} |\n",
        encoding="utf-8",
    )
    return path


def _argv(tmp_path: Path, corpus: dict[str, Any], document: Path, **extra) -> list[str]:
    argv = [
        "--dry-run",
        "--repeats", "1",
        "--metering-run", str(document),
        "--speech-set", str(extra.pop("speech_set", corpus["manifest"])),
        "--speech-clips", str(corpus["clips"]),
        "--out", str(tmp_path / "report.json"),
    ]
    ledger = extra.pop("cost_ledger", tmp_path / "probe.cost_ledger.sqlite3")
    if ledger is not None:
        argv += ["--cost-ledger", str(ledger)]
    for flag, value in extra.items():
        argv += [f"--{flag.replace('_', '-')}", str(value)]
    return argv


def _run(tmp_path: Path, corpus: dict[str, Any], document: Path, **extra):
    code = measure.main(_argv(tmp_path, corpus, document, **extra))
    return code, tmp_path / "report.json"


def _condition(outcome, number):
    for entry in outcome["conditions"]:
        if entry["condition"] == number:
            return entry
    raise AssertionError(f"no condition {number}")


# ── the rehearsal, end to end ────────────────────────────────────────────


def test_the_registered_run_reaches_rehearsal_ok(tmp_path, corpus):
    """Every line from the manifest to the verdict, with nothing bought."""
    document = _document(tmp_path / "prereg.md", corpus=corpus)
    code, report_path = _run(tmp_path, corpus, document)
    assert code == 0

    outcome = checker.check(report_path)
    assert outcome["counts"]["failed"] == 0, [
        entry for entry in outcome["conditions"] if entry["result"] == "fail"
    ]
    assert outcome["verdict"] == checker.VERDICT_REHEARSAL_OK
    assert outcome["record_kind"] == "rehearsal"
    # Condition 2 is the one a stub cannot answer, and it is recorded as
    # unanswerable rather than passed. A rehearsal that scored nine of nine
    # would be the artifact most easily mistaken for the paid run.
    assert _condition(outcome, 2)["result"] == checker.RESULT_UNANSWERABLE
    # 343 §2.2 quotes this line, and 343 §3.5 says the eight endings did not
    # move it. Both claims are only as good as an exact count: "nothing
    # failed" plus "condition 2 is unanswerable" would still hold if a second
    # condition quietly stopped answering, and the document would go on
    # reporting 8/0/1.
    assert outcome["counts"] == {"passed": 8, "failed": 0, "unanswerable": 1}
    assert "8 passed, 0 failed, 1 unanswerable" in checker.render(outcome)
    assert checker.main([str(report_path)]) == 0


