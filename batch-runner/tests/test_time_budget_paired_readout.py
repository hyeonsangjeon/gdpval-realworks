def _capture(seed, parent, index=0, *, terminal="completed", cleanup=True):
    order = scheduling.build_schedule(seed.plan)
    item = order[index]
    base = parent / str(item.sequence)
    base.mkdir()
    arguments = _handoff_arguments(seed, base, condition=item.condition, repeat=item.repeat,
                                   task_index=scheduling.TASK_IDS.index(item.task_id))
    handoff = registration.prepare_observation_handoff(seed.plan, **arguments)
    observation = ObservationIdentity(**handoff["observation"])
    original = base / "capture"
    original.mkdir()
    upload = original / "upload"
    upload.mkdir()
    success = terminal == "completed" and cleanup
    records = []
    if success:
        role = f"deliverable_files/{item.task_id}/fixture.txt"
        path = upload / role
        path.parent.mkdir(parents=True)
        path.write_bytes(f"Synthetic cell {item.sequence}; not generated by a model.\n".encode())
        records = [{"path": role, **_identity(path.read_bytes())}]
    payload = {"experiment_id": item.run_id, "condition": item.condition,
        "fixture_evidence_kind": subject.EVIDENCE,
        "execution_mode": "codex_foundry" if item.condition == "codex" else "agentic_sandbox_v2",
        "model": "gpt-5.4", "source": "openai/gdpval",
        # Explicit fixture retained-origin values, not a private repository read.
        "source_repo_id": "fixture/time-budget", "source_revision": "e" * 40,
        "time_budget_observation": {"policy": "time_budget_observation_deadline_v1",
            "identity": asdict(observation), "admitted": True, "terminal_reason": terminal,
            "cleanup_complete": cleanup, "host_reusable": cleanup,
            "remote_cancellation_confirmed": False, "remote_billing_bound": False},
        "observation_execution": {"host": {"policy": subject.RUNNER_HOST_POLICY,
            "instance_sha256": "f" * 64, "ci_instance_sha256": "a" * 64,
            "ownership_confirmed": False, "runner_image": deepcopy(IMAGE)}},
        "results": [{"task_id": item.task_id, "status": "success" if success else "error",
            "error": None if success else "synthetic_non_success", "retried": False,
            "resume_round": None, "deliverable_files": [row["path"] for row in records],
            "deliverable_file_records": records}]}
    arguments = {name: value for name, value in arguments.items() if name not in {"run_id", "task_id"}}
    arguments.update(observation=observation, expected_input_binding=handoff["inputs"],
        result_path=original / "result.json", deliverables_root=upload,
        destination=base / "publications" / "grading")
    capture = subject.FixtureCapture(item.binding(order), arguments)
    _store_capture(capture, payload)
    # This is the actual scheduler's metadata builder, not a fabricated ID.
    record = scheduling.capture_record(
        {"plan": seed.plan, "cell": item.cell, "request": {"source": {
            "sha": seed.runtime_sha, "tree": seed.runtime_tree}}},
        {"claim": {"synthetic": True}, "returned_commit": "d" * 40},
        {"execution_receipt": {"outcome": "returned"}}, payload)
    (original / scheduling.CAPTURE_NAME).write_text(registration._canonical_json(record))
    assert record["binding"] == capture.binding
    return capture


def _store_capture(capture, payload):
    payload["result_fingerprint"] = inference_result_fingerprint(payload)
    data = registration._canonical_json(payload).encode()
    capture.arguments["result_path"].write_bytes(data)
    capture.arguments["expected_result_identity"] = _identity(data)


def _stub(prepared, plan, monkeypatch, *, points=2, mode="complete"):
    """Serialize an explicit local verdict with F; never construct a Grader."""
    marker = json.loads((prepared.directory / preparation.READY).read_bytes())
    observation = marker["observation"]
    item = scheduling.select(scheduling.build_schedule(registration.load_registration()),
                            {key: observation[key] for key in prepared.binding["cell"]})
    checked = subject._checked_preparation(prepared, item, plan)
    batch = prepared.directory / "source/batch-runner"
    spec = importlib.util.spec_from_file_location("frozen_fixture_step8", batch / "step8_grade.py")
    frozen = importlib.util.module_from_spec(spec)
    monkeypatch.setitem(sys.modules, spec.name, frozen)
    spec.loader.exec_module(frozen)
    config, result = checked["config"], checked["result"]
    config_path = prepared.directory / preparation.CONFIG
    assert frozen.compute_grader_source_hash(config_path, config, batch_root=batch) == (
        marker["grader"]["materialized_source_sha256"])
    selected, _ = frozen.filter_tasks_for_config(result, config, tasks_csv=item.task_id, limit=1)
    assert [row["task_id"] for row in selected] == [item.task_id]
    rubric = config["rubric"]
    loader = subject.RubricLoader(rubric["repo_id"], rubric["revision"], str(prepared.directory / preparation.CACHE))
