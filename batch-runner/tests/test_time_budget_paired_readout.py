    task_rubric = loader._load_tasks_from_parquet(snapshot)[item.task_id]
    assert len(task_rubric.rubric_items) == 1 and task_rubric.rubric_items[0].score == 4
    rows = []
    if mode != "partial":
        criterion = task_rubric.rubric_items[0]
