def _pair_inputs(seed, tmp_path, *, terminal="completed", cleanup=True):
    return [_capture(seed, tmp_path, index, terminal=terminal if index == 0 else "completed", cleanup=cleanup)
            for index in (0, 5)]


def test_twenty_captures_reach_F_once_and_ten_pairs(handoff_sources, tmp_path, monkeypatch, record_property):
    seed = handoff_sources
    captures = [_capture(seed, tmp_path, index) for index in range(20)]
    assert [value.binding["observation_id"] for value in captures] == [
        item.observation_id for item in scheduling.build_schedule(registration.load_registration())]
    prepared = subject.prepare_fixture_captures(seed.plan, list(reversed(captures)))
    assert len(prepared) == len({entry.binding["observation_id"] for entry in prepared}) == 20
    assert [entry.binding["sequence"] for entry in prepared] == list(range(1, 21))
    grades = []
    for entry, capture in zip(prepared, captures):
        marker = json.loads((entry.directory / preparation.READY).read_bytes())
        assert marker["grading_attempt"] == 1
        assert marker["launch_allowed"] is marker["execution_enabled"] is False
        assert (entry.directory / preparation.RESULT).read_bytes() == capture.arguments["result_path"].read_bytes()
        assert (entry.directory / marker["grader"]["entrypoint"]).read_bytes() == (
            seed.frozen / "batch-runner/step8_grade.py").read_bytes()
        points = {("sandbox_v2", 1): 3, ("codex", 1): 1, ("sandbox_v2", 2): 4, ("codex", 2): 2}
        grades.append(_stub(entry, seed.plan, monkeypatch, points=points[entry.binding["cell"]["condition"],
                                                            entry.binding["cell"]["repeat"]]))
    result = subject.aggregate_fixture_pairs(seed.plan, prepared, list(reversed(grades)))
    assert (result["expected_observations"], result["prepared_observations"], result["stub_grades"]) == (20, 20, 20)
    assert (result["expected_pairs"], result["complete_pairs"], result["missing_pairs"]) == (10, 10, 0)
    assert [(pair["task_id"], pair["repeat"]) for pair in result["pairs"]] == [
        (task, repeat) for task in scheduling.TASK_IDS for repeat in (1, 2)]
    assert all(pair["score_difference_pp"] == 50 for pair in result["pairs"])
    assert result["mean_score_difference_pp"] == 50 and result["mean_difference_denominator"] == 10
    assert result["evidence_kind"] == subject.EVIDENCE
    assert result["launch_allowed"] is result["execution_enabled"] is False
    output = tmp_path / "fixture-paired-readout.json"
    output.write_text(registration._canonical_json(result))
    record_property("fixture_readout", str(output))
    record_property("evidence_kind", subject.EVIDENCE)
    record_property("fixture_summary", json.dumps({key: result[key] for key in (
        "expected_observations", "prepared_observations", "stub_grades", "expected_pairs",
        "complete_pairs", "missing_pairs", "mean_score_difference_pp", "mean_difference_denominator")}))
    # A second materialization cannot overwrite or adopt a previous input.
    before = [(entry.directory / preparation.READY).read_bytes() for entry in prepared]
    with pytest.raises(subject.PairedReadoutRefused, match="capture_preparation_refused"):
        subject.prepare_fixture_captures(seed.plan, captures)
    assert before == [(entry.directory / preparation.READY).read_bytes() for entry in prepared]


@pytest.mark.parametrize("case,reason", [
    ("duplicate", "duplicate_observation"), ("outside", "observation_not_registered"),
    ("position", "observation_binding_mismatch"), ("repeat_bool", "observation_binding_mismatch"),
    ("21", "observation_limit_exceeded"), ("cell", "capture_cell_mismatch"),
    ("old_image", "runner_image_mismatch"), ("no_image", "runner_image_mismatch"),
    ("label_only", "runner_image_mismatch"), ("result_hash", "capture_preparation_refused"),
    ("deliverable_hash", "capture_preparation_refused"), ("live", "fixture_evidence_required"),
    ("unlabelled_capture_bytes", "fixture_evidence_required"),
])
def test_bad_capture_inventory_stops_before_preparation(handoff_sources, tmp_path, case, reason):
    capture = _capture(handoff_sources, tmp_path)
    values = [capture]
    if case == "duplicate":
        values *= 2
    elif case == "21":
        values *= 21
    elif case == "outside":
        capture.binding["observation_id"] = "0" * 64
    elif case == "position":
        capture.binding["abba_position"] = 4
    elif case == "repeat_bool":
        capture.binding["cell"]["repeat"] = True
    elif case == "cell":
        capture.arguments["observation"] = replace(capture.arguments["observation"], task_id=scheduling.TASK_IDS[1])
    elif case in {"old_image", "no_image", "label_only"}:
        payload = json.loads(capture.arguments["result_path"].read_bytes())
        host = payload["observation_execution"]["host"]
        if case == "no_image":
            del host["runner_image"]
        else:
            host["runner_image"].update(image_os="ubuntu22", os_version_id="22.04")
            host["runner_image"]["runner"] = "ubuntu-22.04" if case == "old_image" else "ubuntu-24.04"
        _store_capture(capture, payload)
    elif case == "result_hash":
        capture.arguments["result_path"].write_bytes(b"{}")
    elif case == "deliverable_hash":
        next(capture.arguments["deliverables_root"].rglob("fixture.txt")).write_bytes(b"changed")
    elif case == "live":
        values = [replace(capture, evidence_kind="measured")]
    elif case == "unlabelled_capture_bytes":
        payload = json.loads(capture.arguments["result_path"].read_bytes())
        del payload["fixture_evidence_kind"]
        _store_capture(capture, payload)
    with pytest.raises(subject.PairedReadoutRefused, match="^" + reason + "$"):
        subject.prepare_fixture_captures(handoff_sources.plan, values)
    destination = capture.arguments["destination"]
    assert not destination.exists()
    assert not destination.with_name(destination.name + preparation.RESERVATION_SUFFIX).exists()


@pytest.mark.parametrize("case", ["ubuntu22", "different_ubuntu24_image", "source"])
def test_mixed_inventory_refused_before_any_F_input(handoff_sources, tmp_path, case):
    captures = _pair_inputs(handoff_sources, tmp_path)
    changed = captures[1]
    payload = json.loads(changed.arguments["result_path"].read_bytes())
    if case == "source":
        changed.arguments["observation"] = replace(changed.arguments["observation"], reviewed_source_sha="a" * 40)
        payload["time_budget_observation"]["identity"] = asdict(changed.arguments["observation"])
    else:
        image = payload["observation_execution"]["host"]["runner_image"]
        if case == "ubuntu22":
            image.update(runner="ubuntu-22.04", image_os="ubuntu22", os_version_id="22.04")
        else:
            image["image_version"] = "20261031.1.0"
    _store_capture(changed, payload)
    with pytest.raises(subject.PairedReadoutRefused, match="capture_source_mismatch|runner_image_mismatch"):
        subject.prepare_fixture_captures(handoff_sources.plan, captures)
    assert all(not value.arguments["destination"].exists() for value in captures)


@pytest.mark.parametrize("case", ["one_sided", "grade_missing", "empty", "zero", "partial", "judge_error", "denominator_zero"])
def test_missing_is_not_zero_and_pair_denominator_is_explicit(handoff_sources, tmp_path, monkeypatch, case):
    captures = [] if case == "empty" else _pair_inputs(handoff_sources, tmp_path)
    if case == "one_sided":
        captures = captures[:1]
    prepared = subject.prepare_fixture_captures(handoff_sources.plan, captures)
    grades = [_stub(value, handoff_sources.plan, monkeypatch, points=0 if case == "zero" else 2,
                    mode=case if case in {"partial", "judge_error", "denominator_zero"} and index == 0 else "complete")
              for index, value in enumerate(prepared)]
    if case == "grade_missing":
        grades = grades[1:]
    result = subject.aggregate_fixture_pairs(handoff_sources.plan, prepared, grades)
    pair = result["pairs"][0]
    complete = case == "zero"
    assert pair["status"] == ("complete" if complete else "missing")
    assert pair["score_difference_pp"] == (0 if complete else None)
    assert result["mean_difference_denominator"] == (1 if complete else 0)
    assert result["mean_score_difference_pp"] == (0 if complete else None)
    assert result["expected_pairs"] == 10 and len(result["observations"]) == 20
    assert result["complete_pairs"] + result["missing_pairs"] == 10
    if not complete:
        missing_sides = [side for side in (pair["sandbox_v2"], pair["codex"]) if side["missing_reasons"]]
        assert missing_sides and all(side["score_pct"] is None for side in missing_sides)
    if case == "judge_error":
        assert pair["sandbox_v2"]["reported_grade"]["verdicts"] == ["judge_error"]
        assert pair["sandbox_v2"]["reported_grade"]["total_max"] == 0


